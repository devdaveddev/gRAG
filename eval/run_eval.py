"""Retrieval evaluation for gRAG.

Corpus: overlapping Wikipedia articles (fetch_corpus.py). Questions: generated by an LLM from single
"anchor" sentences, so the gold answer location is known. A retrieved chunk is a hit if it contains
>=80% of the anchor sentence's tokens, which is fair across different chunkers.

Compares: vector-only, BM25-only, hybrid (RRF) without rewriting, hybrid with query rewriting,
on fixed-size vs semantic chunking. A conversational set (pronoun follow-ups) isolates the effect of
rewriting with chat history.

    python eval/run_eval.py corpus.json out_dir
"""
import json
import os
import random
import re
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "backend"))
import core  # noqa: E402
from langchain_community.vectorstores.utils import DistanceStrategy  # noqa: E402,F401
from langchain_neo4j import Neo4jVector  # noqa: E402
from langchain_ollama import ChatOllama  # noqa: E402
from langchain_text_splitters import RecursiveCharacterTextSplitter  # noqa: E402

corpus_path, out_dir = sys.argv[1], sys.argv[2]
os.makedirs(out_dir, exist_ok=True)
SEED, PER_DOC, K = 7, 5, 5
SHORT = {"Apple Inc.": "Apple", "Microsoft": "Microsoft", "Google": "Google", "Nvidia": "Nvidia", "OpenAI": "OpenAI",
         "Tesla, Inc.": "Tesla", "Amazon (company)": "Amazon", "Meta Platforms": "Meta"}

cfg = core.Config(neo4j_uri="bolt://localhost:7687", neo4j_user="neo4j", neo4j_password="grag-local-pw", provider="ollama")
g = core.GraphRAG(cfg)
tok = lambda s: set(re.findall(r"[a-z0-9]+", s.lower()))  # noqa: E731


def log(*a):
    print(time.strftime("%H:%M:%S"), *a, flush=True)


# ---------- corpus ----------
raw = json.load(open(corpus_path))
docs = {t: core.clean_text(re.sub(r"\n=+ .*? =+\n", "\n\n", x)) for t, x in raw.items()}

# ---------- questions ----------
qpath = os.path.join(out_dir, "questions.json")
if os.path.exists(qpath):
    questions = json.load(open(qpath))
else:
    gen = ChatOllama(model="qwen2.5:3b", temperature=0)
    rnd = random.Random(SEED)
    questions = []
    for title, text in docs.items():
        sents = [s.strip() for s in re.split(r"(?<=[.!?])\s+(?=[A-Z0-9])", text) if 130 <= len(s) <= 320]
        for anchor in rnd.sample(sents, PER_DOC):
            prompt = (
                f"Sentence: {anchor}\n\nWrite ONE specific question that this sentence answers. "
                "Do not copy more than 3 consecutive words from the sentence; paraphrase instead. "
                f"Mention the subject ({SHORT[title]}) by name. Output only the question."
            )
            q = gen.invoke(prompt).content.strip().split("\n")[0]
            questions.append({"doc": title, "anchor": anchor, "question": q})
            log("Q:", q)
    json.dump(questions, open(qpath, "w"), indent=1)

# conversational variants: the company name becomes a pronoun, resolvable only from history
conv = []
for q in questions:
    name = SHORT[q["doc"]]
    if name in q["question"]:
        conv.append({**q, "question": q["question"].replace(name, "it", 1),
                     "history": [{"role": "user", "text": f"Tell me about {name}."},
                                 {"role": "bot", "text": f"{name} is a technology company."}]})
log(f"{len(questions)} questions, {len(conv)} conversational")

# ---------- retrieval variants ----------
rw_cache: dict = {}
real_rewrite = g.rewrite_query


def cached_rewrite(question, history):
    key = (question, json.dumps(history))
    if key not in rw_cache:
        rw_cache[key] = real_rewrite(question, history)
    return rw_cache[key]


identity = lambda q, h: {"standalone": q, "variants": [], "keywords": []}  # noqa: E731


def retrieve(method, q, history):
    if method == "vector":
        return [h["text"] for h in g._semantic(q, K)]
    if method == "bm25":
        return [h["text"] for h in g._bm25(q, K)]
    g.rewrite_query = identity if method == "hybrid" else cached_rewrite
    return [c["text"] for c in g.hybrid_search(q, history, top_n=K)["chunks"]]


def hit(chunk, anchor):
    a = tok(anchor)
    return len(a & tok(chunk)) / len(a) >= 0.8


def score(method, items):
    ranks = []
    for it in items:
        res = retrieve(method, it["question"], it.get("history", []))
        r = next((i + 1 for i, c in enumerate(res) if hit(c, it["anchor"])), None)
        ranks.append(r)
    n = len(ranks)
    rec = lambda k: sum(1 for r in ranks if r and r <= k) / n  # noqa: E731
    return {"n": n, "recall@1": rec(1), "recall@3": rec(3), "recall@5": rec(5),
            "mrr@5": sum(1 / r for r in ranks if r) / n}


# ---------- chunkers ----------
def fixed_chunks(text):
    return RecursiveCharacterTextSplitter(chunk_size=1500, chunk_overlap=150).split_text(text)


results = {}
for name, chunker in (("fixed-1500", fixed_chunks), ("semantic", g.smart_chunks)):
    chunks = [c for t in docs.values() for c in chunker(t)]
    lens = [len(c) for c in chunks]
    log(f"[{name}] {len(chunks)} chunks, mean {sum(lens)/len(lens):.0f} chars")
    g.graph.query("MATCH (n:Chunk) DETACH DELETE n")
    g.graph.query(f"DROP INDEX {core.VECTOR_INDEX} IF EXISTS")
    Neo4jVector.from_texts(chunks, g.embeddings, ids=[f"c{i}" for i in range(len(chunks))],
                           url=cfg.neo4j_uri, username=cfg.neo4j_user, password=cfg.neo4j_password,
                           index_name=core.VECTOR_INDEX, node_label="Chunk", text_node_property="text")
    g.ensure_indexes()
    g.graph.query("CALL db.awaitIndexes(120)")
    results[name] = {"chunks": len(chunks), "mean_chars": round(sum(lens) / len(lens))}
    for setname, items in (("single-turn", questions), ("conversational", conv)):
        for method in ("vector", "bm25", "hybrid", "hybrid+rewrite"):
            m = score(method, items)
            results[name][f"{setname}/{method}"] = m
            log(f"[{name}] {setname:14s} {method:15s}", {k: round(v, 3) for k, v in m.items()})
    json.dump(results, open(os.path.join(out_dir, "results.json"), "w"), indent=1)
log("done")
